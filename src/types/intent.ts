import { z } from "zod";

export const INTENT_NAMES = [
  "create_task",
  "list_tasks",
  "update_task",
  "complete_task",
  "delete_task",
  "create_reminder",
  "cancel_reminder",
  "snooze_reminder",
  "list_reminders",
  "save_note",
  "search_notes",
  "update_note",
  "delete_note",
  "save_document",
  "search_documents",
  "summarize_document",
  "send_document",
  "search_knowledge",
  "save_knowledge",
  "prepare_incident_report",
  "generate_daily_summary",
  "prepare_shift_handover",
  "improve_english",
  "help",
  "clarify",
] as const;

export type IntentName = (typeof INTENT_NAMES)[number];

export const IntentSchema = z.object({
  intent: z.enum(INTENT_NAMES),
  confidence: z.number().min(0).max(1),
  clarification_question: z.string().max(500),
  title: z.string().max(200),
  details: z.string().max(8000),
  category: z.string().max(80),
  priority: z.enum(["", "low", "normal", "high", "urgent"]),
  status: z.enum(["", "pending", "in_progress", "completed", "cancelled"]),
  when_text: z.string().max(200),
  recurrence: z.enum(["", "once", "daily", "weekly", "interval", "daily_summary"]),
  entity_number: z.number().int().nonnegative().max(1_000_000),
  search_query: z.string().max(200),
  tags: z.string().max(200),
  snooze_minutes: z.number().int().nonnegative().max(10_080),
  interval_minutes: z.number().int().nonnegative().max(10_080),
  list_filter: z.enum(["", "pending", "today", "overdue"]),
});

export type Intent = z.infer<typeof IntentSchema>;

export const INTENT_JSON_SCHEMA: Record<string, unknown> = {
  type: "object",
  additionalProperties: false,
  required: [
    "intent",
    "confidence",
    "clarification_question",
    "title",
    "details",
    "category",
    "priority",
    "status",
    "when_text",
    "recurrence",
    "entity_number",
    "search_query",
    "tags",
    "snooze_minutes",
    "interval_minutes",
    "list_filter",
  ],
  properties: {
    intent: { type: "string", enum: [...INTENT_NAMES] },
    confidence: { type: "number" },
    clarification_question: { type: "string" },
    title: { type: "string" },
    details: { type: "string" },
    category: { type: "string" },
    priority: { type: "string", enum: ["", "low", "normal", "high", "urgent"] },
    status: { type: "string", enum: ["", "pending", "in_progress", "completed", "cancelled"] },
    when_text: { type: "string" },
    recurrence: { type: "string", enum: ["", "once", "daily", "weekly", "interval", "daily_summary"] },
    entity_number: { type: "integer" },
    search_query: { type: "string" },
    tags: { type: "string" },
    snooze_minutes: { type: "integer" },
    interval_minutes: { type: "integer" },
    list_filter: { type: "string", enum: ["", "pending", "today", "overdue"] },
  },
};

export function blankIntent(partial: Partial<Intent> & Pick<Intent, "intent">): Intent {
  return {
    intent: partial.intent,
    confidence: partial.confidence ?? 0.95,
    clarification_question: partial.clarification_question ?? "",
    title: partial.title ?? "",
    details: partial.details ?? "",
    category: partial.category ?? "",
    priority: partial.priority ?? "",
    status: partial.status ?? "",
    when_text: partial.when_text ?? "",
    recurrence: partial.recurrence ?? "",
    entity_number: partial.entity_number ?? 0,
    search_query: partial.search_query ?? "",
    tags: partial.tags ?? "",
    snooze_minutes: partial.snooze_minutes ?? 0,
    interval_minutes: partial.interval_minutes ?? 0,
    list_filter: partial.list_filter ?? "",
  };
}
